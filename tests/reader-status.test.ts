import './setup.ts';
import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {sql,closeDb} from '@agidawn/backend/db';
import {installModules} from '@agidawn/backend/modules';
import {upsertMaterial} from '@agidawn/backend/content/materials';
import {stopBoss} from '@agidawn/backend/jobs/queue';
import reader from '../modules/reader/server.ts';
import {archiveSnapshot} from '../modules/reader/archive/assets.ts';
import {readerStatus} from '../scripts/reader-status.ts';
installModules([reader]);
after(async()=>{await stopBoss();await closeDb();});
test('daily observation distinguishes body failures, ignores old partial versions and contains no private content',async()=>{
  await sql`INSERT INTO sources(id,name,kind,health) VALUES ('observed','Observed','rss','ok')`;
  const {articleId}=await upsertMaterial({sourceId:'observed',url:'https://example.com/observed',title:'Observed article',via:'fetch'});
  await sql`UPDATE articles SET body_status='unconfirmed',processing_state='failed',processing_error='原站正文请求 HTTP 403' WHERE id=${articleId}`;
  const retrying=await upsertMaterial({sourceId:'observed',url:'https://example.com/retrying',title:'Retrying',via:'fetch'});
  await sql`UPDATE articles SET processing_state='new',processing_error='原站正文网络请求失败',processing_retry_at=now()+interval '10 minutes' WHERE id=${retrying.articleId}`;
  await sql`INSERT INTO reader_assets(hash,mime,bytes,path) VALUES (${'b'.repeat(64)},'image/png',1024,${'b'.repeat(64)+'.png'})`;
  const material={sourceId:'observed',url:'https://example.com/versioned-report',title:'Versioned',via:'fetch' as const,bodyStatus:'ok' as const,bodyText:'body-private-sentinel',bodyHtml:'<p>body-private-sentinel</p>'};
  const saved=await upsertMaterial({...material,bodyQuality:'partial',bodyIssues:[{kind:'missing-figure',message:'Old missing drawing'}]});
  const [old]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${saved.articleId}`;await archiveSnapshot(old!.id);
  await upsertMaterial({...material,bodyHtml:'<p><strong>body-private-sentinel</strong></p>'});
  const [current]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${saved.articleId} AND id<>${old!.id}`;await archiveSnapshot(current!.id);
  await sql`INSERT INTO reader_notes(article_id,text) VALUES (${saved.articleId},'note-private-sentinel')`;
  const report=await readerStatus(new Date('2026-10-28T02:00:00Z'),new Date('2026-10-28T00:00:00Z'));
  const source=report.sources.find(row=>row.id==='observed')!;
  assert.equal(source.health,'ok');assert.equal(source.bodyFailed,1);assert.equal(source.bodies,1);
  assert.equal(source.bodyRetrying,1);assert.equal(report.failures.find(row=>row.articleId===retrying.articleId)!.processingState,'new');
  assert.equal(report.assets.files,1);assert.equal(report.assets.bytes,1024);
  assert.equal(report.archives.complete,1);assert.equal(report.archives.partial,0);
  assert.equal(report.observation.windowElapsed,false);assert.equal(report.observation.elapsedHours,2);
  assert.ok(!JSON.stringify(report).includes('private-sentinel'));
  assert.equal((await readerStatus(new Date('2026-11-04T00:00:00Z'),new Date('2026-10-28T00:00:00Z'))).observation.windowElapsed,true);
});

import "../../../tests/setup.ts";
import assert from "node:assert/strict";
import {test,after} from "node:test";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {mkdtemp,mkdir,readFile,writeFile,rm} from "node:fs/promises";
import {tmpdir} from "node:os";
import path from "node:path";
import sharp from "sharp";
import {sql,closeDb} from "@agidawn/backend/db";
import {config} from "@agidawn/backend/config";
import {installModules} from "@agidawn/backend/modules";
import {upsertMaterial} from "@agidawn/backend/content/materials";
import {runBackup} from "@agidawn/backend/operations/backup";
import {stopBoss} from "@agidawn/backend/jobs/queue";
import {sha256} from "@agidawn/backend/lib/ids";
import reader from "../server.ts";
import {archiveSnapshot} from "../archive/assets.ts";
import {readNote} from "../notes.ts";
import {readState} from "../state.ts";
import {addView,updateView} from "../views.ts";
import {savePosition} from "../positions.ts";
const run=promisify(execFile),originalData=config.dataDir,dirs:string[]=[],databases:string[]=[];
installModules([reader]);
after(async()=>{config.dataDir=originalData;await stopBoss();for(const name of databases)await sql.unsafe(`DROP DATABASE "${name}" WITH (FORCE)`);await closeDb();for(const dir of dirs)await rm(dir,{recursive:true,force:true});});
test("a local-only backup restores private notes, state, views, positions and verified assets into a new database and directory",async()=>{
  const started=performance.now(),root=await mkdtemp(path.join(tmpdir(),"reader-paired-"));dirs.push(root);config.dataDir=root;
  await sql`INSERT INTO sources(id,name,kind,tier,participation_mode,site_fulltext) VALUES ('restore-reader','Restore source','rss','T1','editorial',true)`;
  const bytes=await sharp({create:{width:40,height:30,channels:3,background:"#145b54"}}).png().toBuffer();
  const {articleId}=await upsertMaterial({sourceId:"restore-reader",title:"Restored article",url:"https://example.com/restored",bodyHtml:`<h2>Saved section</h2><p>Restored original body</p><img alt="Restored image" src="data:image/png;base64,${bytes.toString("base64")}">`,bodyText:"Saved section Restored original body",bodyStatus:"ok",via:"fetch"});
  const [snapshot]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${articleId}`;await archiveSnapshot(snapshot!.id);
  await sql`INSERT INTO reader_notes(article_id,text,version) VALUES (${articleId},'Restore note sentinel',7)`;
  await sql`INSERT INTO reader_state(article_id,starred,status,version) VALUES(${articleId},true,'reading',5)`;
  const created=await addView({name:'Restore saved view',filters:{q:'Restore note sentinel',sourceId:'restore-reader',starred:'true',status:'reading',hasNote:'true',sort:'note-updated'}},'restore-test');
  const view=await updateView(created.id,{expectedVersion:1,name:'Restored note review'},'restore-test');
  await savePosition(snapshot!.id,{expectedVersion:0,anchor:'sec-1',offset:0.1,progress:0.2});
  const position=await savePosition(snapshot!.id,{expectedVersion:1,anchor:'sec-1',offset:0.3,progress:0.4});
  const expected={note:await readNote(articleId),state:await readState(articleId),view,position};
  const summary=await runBackup(new Date("2026-10-27T10:00:00Z"),{localOnly:true});
  assert.equal(summary.uploaded,false);assert.equal(summary.complete,true);
  const manifest=JSON.parse(await readFile(summary.group!.manifest,"utf8"));
  for(const artifact of manifest.artifacts){const data=await readFile(path.join(root,"backups",artifact.file));assert.equal(data.length,artifact.bytes);assert.equal(sha256(data),artifact.sha256);}
  const restored=path.join(root,"restored-data");await mkdir(restored);
  await run("tar",["-xzf",summary.group!.files,"-C",restored]);
  const name=`${sql.options.database}_paired_restore_test`;assert.match(name,/^[a-z0-9_]+_test$/);
  await sql.unsafe(`CREATE DATABASE "${name}"`);databases.push(name);
  const connection=new URL(config.databaseUrl);connection.pathname="/"+name;
  const env={...process.env,PGUSER:decodeURIComponent(connection.username),PGPASSWORD:decodeURIComponent(connection.password)};
  connection.username=connection.password="";
  await run("pg_restore",["--exit-on-error","--no-owner","--dbname",connection.href,summary.group!.dump],{env});
  const restoredUrl=new URL(config.databaseUrl);restoredUrl.pathname="/"+name;
  const validation=await run(process.execPath,["--input-type=module","--eval",`
    import assert from "node:assert/strict";
    import {sql,closeDb} from "@agidawn/backend/db";
    import {config} from "@agidawn/backend/config";
    import {verifyReaderArchive} from "./modules/reader/archive/verify.ts";
    import {exportSnapshot} from "./modules/reader/archive/export.ts";
    import {readNote} from "./modules/reader/notes.ts";
    import {readState,readLibrary} from "./modules/reader/state.ts";
    import {readView} from "./modules/reader/views.ts";
    import {readPosition} from "./modules/reader/positions.ts";
    import {exportNote,exportNotes} from "./modules/reader/note-export.ts";
    import {unzipSync,strFromU8} from "fflate";
    try {
      const expected=JSON.parse(process.env.RESTORED_EXPECTED),id=process.env.RESTORED_ARTICLE;
      const privateRows=async()=>({notes:await sql\`SELECT * FROM reader_notes ORDER BY article_id\`,state:await sql\`SELECT * FROM reader_state ORDER BY article_id\`,views:await sql\`SELECT * FROM reader_saved_views ORDER BY id\`,positions:await sql\`SELECT * FROM reader_positions ORDER BY article_id,body_hash\`,audit:await sql\`SELECT * FROM audit_log ORDER BY id\`}),before=await privateRows();
      assert.deepEqual(await readNote(id),expected.note);assert.deepEqual(await readState(id),expected.state);assert.deepEqual(await readView(expected.view.id),expected.view);
      assert.deepEqual(await readPosition(process.env.RESTORED_SNAPSHOT),{position:expected.position,previous:null});
      const library=await readLibrary(expected.view.filters);assert.deepEqual(library.items.map(item=>item.id),[id]);assert(library.items[0].matches.some(match=>match.field==='note'));assert(library.items[0].note.updatedAt===expected.note.updatedAt);
      assert.equal((await readLibrary({sourceId:'restore-reader',q:'original body'})).items[0].id,id,'restored current body is searchable');
      const single=await exportNote(id),notes=unzipSync(await exportNotes({articleIds:[id]}));assert.equal(strFromU8(notes[single.filename]),single.text);assert(single.text.endsWith(expected.note.text+'\\n'));assert(single.text.includes('note_version: 7'));
      const result=await verifyReaderArchive(config.dataDir);assert.equal(result.assets,1);
      const bundle=await exportSnapshot(process.env.RESTORED_SNAPSHOT);
      const chunks=[];for await(const chunk of bundle.stream)chunks.push(chunk);
      const files=unzipSync(Buffer.concat(chunks));assert.ok(Buffer.from(files["article.html"]).includes("Restored original body"));assert(!Buffer.from(files['article.html']).includes(expected.note.text));
      assert.deepEqual(await privateRows(),before,'restored search, reading and exports are read-only');
      console.log(JSON.stringify({notes:1,state:1,views:1,positions:1,assets:result.assets,exportFiles:Object.keys(files).length}));
    } finally {await closeDb();}
  `],{cwd:process.cwd(),env:{...process.env,DATABASE_URL:restoredUrl.href,AGIDawn_DATA_DIR:restored,RESTORED_ARTICLE:articleId,RESTORED_SNAPSHOT:snapshot!.id,RESTORED_EXPECTED:JSON.stringify(expected)}});
  assert.match(validation.stdout,/"assets":1/);
  const [asset]=await sql`SELECT path FROM reader_assets LIMIT 1`;
  await writeFile(path.join(root,"reader-archives/assets",asset!.path),"corrupt");
  await assert.rejects(runBackup(new Date("2026-10-27T10:01:00Z"),{localOnly:true}),/checksum|corrupt|size/);
  await assert.rejects(readFile(path.join(root,"backups",path.basename(summary.group!.manifest).replace("1000","1001"))),/ENOENT/);
  console.log(JSON.stringify({restoreMs:Math.round(performance.now()-started),database:name,articles:1,notes:1,assets:1}));
});

test("a specified snapshot exports frozen offline files without private notes or automatic network access",async()=>{
  await sql`INSERT INTO sources(id,name,kind,tier,participation_mode,site_fulltext) VALUES ('export-reader','Export source','rss','T1','editorial',true)`;
  const image=await sharp({create:{width:40,height:30,channels:3,background:"#145b54"}}).png().toBuffer();
  const material={sourceId:"export-reader",url:"https://example.com/offline",title:"Frozen version A",bodyText:"Version A code table",bodyHtml:`<h2>Version A</h2><pre><code class="language-python">print("offline")</code></pre><table><tr><th>Method</th><th>Value</th></tr><tr><td>Saved</td><td>42</td></tr></table><img alt="Diagram" src="data:image/png;base64,${image.toString("base64")}">`,bodyStatus:"ok" as const,via:"fetch" as const};
  const {articleId}=await upsertMaterial(material);
  const [snapshot]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${articleId}`;
  await archiveSnapshot(snapshot!.id);
  await sql`INSERT INTO reader_notes(article_id,text) VALUES (${articleId},'private-note-sentinel')`;
  const route=`/api/admin/reader/snapshots/${snapshot!.id}/export.zip`;
  assert.equal((await app.inject(route)).statusCode,401);
  config.devAdmin=null;config.adminPassword="export-long-test-password";
  const {token}=await passwordLogin(config.adminPassword,"/admin/reader","test"),headers={cookie:`${SESSION_COOKIE}=${token}`};
  await upsertMaterial({...material,title:"New version B",bodyHtml:"<p>Version B</p>",bodyText:"Version B"});
  const response=await app.inject({url:route,headers});
  assert.equal(response.statusCode,200);
  assert.equal(response.headers["cache-control"],"no-store");
  const files=unzipSync(response.rawPayload),text=(key:string)=>Buffer.from(files[key]!).toString("utf8");
  const manifest=JSON.parse(text("metadata.json"));
  assert.equal(manifest.snapshotId,snapshot!.id);assert.equal(manifest.completeness,"complete");
  assert.ok(text("article.html").includes("Frozen version A")&&!text("article.html").includes("Version B"));
  assert.ok(!Object.values(files).some(value=>Buffer.from(value).includes("private-note-sentinel")));
  for(const file of manifest.files) {assert.equal(files[file.path]!.length,file.bytes);assert.equal(sha256(Buffer.from(files[file.path]!)),file.sha256);}
  assert.match(text("article.md"),/!\[Diagram\]\(assets\/[a-f0-9]+\.png\)/);
  const dir=await mkdtemp(path.join(tmpdir(),"reader-offline-"));
  const browser=await chromium.launch();
  try {
    for(const [name,bytes] of Object.entries(files)){assert.ok(!name.startsWith("/")&&!name.includes(".."));await mkdir(path.dirname(path.join(dir,name)),{recursive:true});await writeFile(path.join(dir,name),bytes);}
    const page=await browser.newPage();let requests=0;
    await page.route(/^https?:/,route=>{requests++;return route.abort();});
    await page.goto(pathToFileURL(path.join(dir,"article.html")).href);
    await expect(page.getByRole("heading",{name:"Version A",exact:true})).toBeVisible();
    await expect(page.locator("pre")).toContainText('print("offline")');
    await expect(page.locator("table")).toContainText("42");
    assert.equal(await page.locator("img").evaluateAll(images=>images.every(node=>{const image=node as unknown as {complete:boolean;naturalWidth:number};return image.complete&&image.naturalWidth>0;})),true);
    assert.equal(requests,0);
  } finally {await browser.close();await rm(dir,{recursive:true,force:true});}
  assert.equal((await app.inject({url:"/api/admin/reader/snapshots/unknown/export.zip",headers})).statusCode,404);
  const pending=await upsertMaterial({...material,url:"https://example.com/pending-export",bodyHtml:'<p>Partial body</p><img src="https://example.com/missing.png">',bodyText:"Partial body"});
  const [incomplete]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${pending.articleId}`;
  const partial=await app.inject({url:`/api/admin/reader/snapshots/${incomplete!.id}/export.zip`,headers});
  assert.equal(partial.statusCode,200);
  const partialFiles=unzipSync(partial.rawPayload);
  assert.equal(JSON.parse(Buffer.from(partialFiles["metadata.json"]!).toString()).completeness,"partial");
  assert.match(Buffer.from(partialFiles["article.html"]!).toString(),/不完整/);
});

test("export metadata stays literal Markdown and missing resources expose no server paths",async()=>{
  await sql`INSERT INTO sources(id,name,kind) VALUES ('export-metadata','![source](https://example.com/source.png)','rss')`;
  const bytes=await sharp({create:{width:45,height:31,channels:3,background:'#f0b345'}}).png().toBuffer();
  const {articleId}=await upsertMaterial({sourceId:'export-metadata',url:'https://example.com/metadata',title:'![title](https://example.com/title.png) <img src="https://example.com/raw.png">',bodyHtml:`<p>Literal metadata</p><img alt="Saved" src="data:image/png;base64,${bytes.toString('base64')}">`,bodyText:'Literal metadata',bodyStatus:'ok',via:'fetch'});
  const [snapshot]=await sql`SELECT id FROM reader_snapshots WHERE article_id=${articleId}`;
  await archiveSnapshot(snapshot!.id);
  const read=async()=>{const bundle=await exportSnapshot(snapshot!.id),chunks:Buffer[]=[];for await(const chunk of bundle.stream)chunks.push(Buffer.from(chunk));return unzipSync(Buffer.concat(chunks));};
  const files=await read(),html=await marked.parse(Buffer.from(files['article.md']!).toString());
  const $=cheerio.load(html);
  assert.equal($('img').length,1);
  assert.ok($('img').toArray().every(node=>$(node).attr('src')?.startsWith('assets/')));
  const [asset]=await sql`SELECT a.path FROM reader_snapshot_assets sa JOIN reader_assets a ON a.hash=sa.asset_hash WHERE sa.snapshot_id=${snapshot!.id}`;
  await rm(assetFile(asset!.path));
  const partial=await read();
  assert.equal(JSON.parse(Buffer.from(partial['metadata.json']!).toString()).completeness,'partial');
  for(const [name,data] of Object.entries(partial))if(!name.startsWith('assets/'))assert.ok(!Buffer.from(data).toString().includes(config.dataDir),name);
});
